"""Explicit plan styling and disclosure delivery for independent video production.

Consumes renderer files; never imports or starts the production orchestrator.
The receipt proves technical checks, not editorial or listening approval.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
from pathlib import Path
import struct
import subprocess

from PIL import Image, ImageFont

from .final_qa import digest
from .post_media_rules import DISCLOSURE_VERSION, disclosure_layer

STYLE_VERSION = 'kcc-cover100-body80-20261025-v1'


def checked_font(path, text, *, family=None):
    path = Path(path).resolve(strict=True)
    font = ImageFont.truetype(str(path), 64)
    if family and font.getname()[0] != family:
        raise ValueError(f'Required font family: {family}; got {font.getname()[0]}')
    def shape(char):
        mask = font.getmask(char)
        return mask.size, bytes(mask)
    missing = {shape('\uffff'), shape('\U0010ffff')}
    if any(shape(char) in missing for char in text if not char.isspace()):
        raise ValueError('Font is missing requested glyphs')
    return path, font.getname()


def apply_current_style(plan, font_path):
    """Return a copy; apply only to a new plan or an explicitly requested restyle."""
    result = copy.deepcopy(plan)
    spec = result['cover_spec']
    path, name = checked_font(font_path, ''.join(spec['lines']), family='KCC-Ganpan')
    # Keep the existing typography geometry, outline, alpha and narration clock.
    spec['style']['shadow_effect']['blur'] = 1.0
    result['caption_style']['shadow_effect']['blur'] = .8
    result['caption_style']['version'] = STYLE_VERSION
    result['cover_font_style'] = {
        'font_path': str(path), 'font_family': name[0], 'font_face': name[1],
        'font_title': 'KCC간판체', 'requested_font': 'KCC간판체',
        'font_weight': result.get('cover_font_style', {}).get('font_weight', 700),
        'font_resource_id': '', 'font_status': 'available',
    }
    # These describe a previous render and must be regenerated by the renderer.
    for field in ('font', 'font_render_check', 'layout'):
        spec.pop(field, None)
    result['hotpost_style'] = {'version': STYLE_VERSION, 'font_sha256': digest(path),
                              'cover_blur_percent': 100, 'caption_blur_percent': 80,
                              'requires_output_review': True}
    return result


def _run(args):
    return subprocess.run(args, check=True, capture_output=True, text=True, encoding='utf8',
                          creationflags=subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0).stdout


def _probe(path):
    return json.loads(_run(['ffprobe', '-v', 'error', '-show_streams', '-of', 'json', str(path)]))['streams']


def _packets(path, stream, *, hashes=False):
    args = ['ffprobe', '-v', 'error', '-select_streams', stream, '-show_packets',
            '-show_entries', 'packet=pts_time,dts_time,duration_time' + (',data_hash' if hashes else ''),
            '-of', 'json']
    if hashes:
        args += ['-show_data_hash', 'sha256']
    return json.loads(_run(args + [str(path)]))['packets']


def _faststart(path):
    atoms = []
    with Path(path).open('rb') as stream:
        length = Path(path).stat().st_size
        while stream.tell() < length:
            start = stream.tell()
            header = stream.read(8)
            if len(header) != 8:
                raise ValueError('Invalid MP4 atom header')
            size, kind = struct.unpack('>I4s', header)
            minimum = 8
            if size == 1:
                size = struct.unpack('>Q', stream.read(8))[0]
                minimum = 16
            if size == 0:
                size = length - start
            if size < minimum or start + size > length:
                raise ValueError('Invalid MP4 atom length')
            atoms.append(kind)
            stream.seek(start + size)
    return b'moov' in atoms and b'mdat' in atoms and atoms.index(b'moov') < atoms.index(b'mdat')


def finalize(raw_video, raw_cover, output, font_path, *, unmarked_inputs=False):
    """Add disclosure once to raw independent-renderer outputs, in a fresh folder."""
    if not unmarked_inputs:
        raise ValueError('Confirm inputs are raw renders without disclosure; never feed delivery output back')
    raw_video, raw_cover = Path(raw_video).resolve(strict=True), Path(raw_cover).resolve(strict=True)
    for path in (raw_video, raw_cover):
        if (path.parent / 'delivery-receipt.json').exists():
            raise ValueError('Already delivered input; use original raw renderer outputs')
    font_path, _ = checked_font(font_path, '[광고]')
    before = {'video': digest(raw_video), 'cover': digest(raw_cover)}
    streams = _probe(raw_video)
    videos = [s for s in streams if s['codec_type'] == 'video']
    audios = [s for s in streams if s['codec_type'] == 'audio']
    if len(videos) != 1 or len(audios) != 1 or audios[0].get('codec_name') != 'aac' or audios[0].get('profile') != 'LC':
        raise ValueError('One video and one AAC-LC audio stream are required')
    size = videos[0]['width'], videos[0]['height']
    audio_packets = _packets(raw_video, 'a:0', hashes=True)
    with Image.open(raw_cover) as original:
        if original.size != size:
            raise ValueError('Cover size differs from video')
        layer = disclosure_layer(size, font_path)
        marked = Image.alpha_composite(original.convert('RGBA'), layer).convert('RGB')
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    cover, video = output / 'cover.png', output / 'video.mp4'
    marked.save(cover)
    layer.save(output / 'disclosure.png')
    # Body gets one layer. Already marked cover replaces frame 0 afterwards.
    graph = "[0:v][2:v]overlay=0:0:format=yuv420[b];[b][1:v]overlay=0:0:enable='eq(n,0)':format=yuv420[v]"
    _run(['ffmpeg', '-v', 'error', '-nostdin', '-n', '-i', str(raw_video), '-i', str(cover),
          '-i', str(output / 'disclosure.png'), '-filter_complex', graph,
          '-map', '[v]', '-map', '0:a:0', '-c:v', 'libx264', '-preset', 'medium', '-crf', '18',
          '-profile:v', 'main', '-level:v', '4.0', '-pix_fmt', 'yuv420p',
          '-maxrate', '12M', '-bufsize', '24M', '-fps_mode', 'passthrough',
          '-c:a', 'copy', '-movflags', '+faststart', str(video)])
    delivered = _probe(video)
    stream = next(s for s in delivered if s['codec_type'] == 'video')
    if (stream['profile'], stream['level'], stream['pix_fmt']) != ('Main', 40, 'yuv420p'):
        raise ValueError('Delivery profile mismatch')
    if (stream['width'], stream['height']) != size:
        raise ValueError('Delivery dimensions changed')
    if audio_packets != _packets(video, 'a:0', hashes=True):
        raise ValueError('Audio packet data or timing changed')
    # Encoding can reorder packet DTS, but presentation times must stay intact.
    before_clock = sorted(p['pts_time'] for p in _packets(raw_video, 'v:0'))
    after_clock = sorted(p['pts_time'] for p in _packets(video, 'v:0'))
    if before_clock != after_clock:
        raise ValueError('Video presentation clock changed')
    if not _faststart(video):
        raise ValueError('Delivery is not faststart')
    _run(['ffmpeg', '-v', 'error', '-xerror', '-nostdin', '-i', str(video), '-f', 'null', '-'])
    if before != {'video': digest(raw_video), 'cover': digest(raw_cover)}:
        raise ValueError('Inputs changed during delivery')
    receipt = {'schema_version': 1, 'quality_complete': False, 'disclosure': DISCLOSURE_VERSION,
               'inputs': {'video': str(raw_video), 'cover': str(raw_cover), 'sha256': before},
               'video': str(video), 'cover': str(cover), 'video_sha256': digest(video),
               'cover_sha256': digest(cover), 'audio_packets_unchanged': True,
               'video_pts_unchanged': True, 'full_decode': True, 'faststart': True,
               'pending_review': ['script', 'visual', 'audio_captions', 'cover_delivery']}
    (output / 'delivery-receipt.json').write_text(json.dumps(receipt, ensure_ascii=False, indent=2), 'utf8')
    return receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    style = commands.add_parser('style-plan')
    style.add_argument('--plan', type=Path, required=True)
    style.add_argument('--font', type=Path, required=True)
    style.add_argument('--output', type=Path, required=True)
    delivery = commands.add_parser('finalize')
    delivery.add_argument('--raw-video', type=Path, required=True)
    delivery.add_argument('--raw-cover', type=Path, required=True)
    delivery.add_argument('--font', type=Path, required=True)
    delivery.add_argument('--output', type=Path, required=True)
    delivery.add_argument('--unmarked-inputs', action='store_true', required=True)
    args = parser.parse_args()
    try:
        if args.command == 'style-plan':
            result = apply_current_style(json.loads(args.plan.read_text('utf8')), args.font)
            with args.output.open('x', encoding='utf8') as stream:
                json.dump(result, stream, ensure_ascii=False, indent=2)
            print(str(args.output))
        else:
            print(json.dumps(finalize(args.raw_video, args.raw_cover, args.output, args.font,
                                      unmarked_inputs=args.unmarked_inputs), ensure_ascii=False, indent=2))
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()
